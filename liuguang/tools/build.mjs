// Build the browser halves of both packages.
//
// The Desktop app boots its renderer from a static index inside app.asar, so
// the host-side index injection never reaches it. The browser half is a plain
// `window.__ModuleLoader__` bundle (the format DSH client plugins ship) that
// the client module graph loads: it applies the baked stylesheet immediately,
// swaps in `/liuguang/theme.css` so CSS edits need only a refresh, and mounts the
// overlay (theme controls + DeepSeek-chan pet) on the `shell.overlay` slot.
//
//   node tools/build.mjs
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const cssPath = join(root, 'lib', 'liuguang.css')
const overlayPath = join(root, 'src', 'overlay.js')
const css = readFileSync(cssPath, 'utf8')
const overlay = readFileSync(overlayPath, 'utf8')
const hash = createHash('sha256').update(css).update(overlay).digest('hex').slice(0, 12)

/** Emit one browser half. `id` must equal the package name; only the browser
 *  face mounts the overlay so the two packages never fight over one slot id. */
function bundle({ id, file, overlay: withOverlay = false }) {
  const text = `// Generated by tools/build.mjs from lib/liuguang.css + src/overlay.js (sha ${hash}) — do not edit by hand.
window.__ModuleLoader__.load({
  id: ${JSON.stringify(id)},
  factory: (require) => {
    var module = { exports: {} };
    try {
    Object.defineProperty(module.exports, Symbol.toStringTag, { value: "Module" });

    const React = require("react");
    const STYLE_ID = "liuguang-skin";
    // Baked copy: first paint is styled even if the live fetch is slow.
    const CSS = ${JSON.stringify(css)};
    const HEX = /^#[0-9a-fA-F]{6}$/;
    const MOTIONS = { full: 1, subtle: 1, none: 1 };
    const DEFAULTS = { accent: "#4fb59a", accent2: "#8ee0c8", blur: 26, glass: 1, motion: "full" };

    // Every knob is validated here too: config must never reach CSS raw.
    function readKnobs(config) {
      const source = config && typeof config === "object" ? config : {};
      const pick = (value, fallback) => typeof value === "string" && HEX.test(value.trim()) ? value.trim() : fallback;
      const clampNumber = (value, min, max, fallback) => {
        const parsed = typeof value === "number" ? value : Number.parseFloat(value);
        return Number.isFinite(parsed) ? Math.min(max, Math.max(min, parsed)) : fallback;
      };
      return {
        accent: pick(source.accent, DEFAULTS.accent),
        accent2: pick(source.accent2, DEFAULTS.accent2),
        blur: clampNumber(source.blur, 0, 60, DEFAULTS.blur),
        glass: clampNumber(source.glass, 0.2, 1, DEFAULTS.glass),
        motion: Object.prototype.hasOwnProperty.call(MOTIONS, source.motion) ? source.motion : DEFAULTS.motion
      };
    }

    function knobVars(knobs) {
      const motion = knobs.motion;
      return ":root{" +
        "--lg-accent:" + knobs.accent + ";" +
        "--lg-accent-2:" + knobs.accent2 + ";" +
        "--lg-glass-blur:" + knobs.blur + "px;" +
        "--lg-glass:" + knobs.glass + ";" +
        "--lg-anim:" + (motion === "none" ? "none" : "liuguang-drift") + ";" +
        "--lg-drift:" + (motion === "subtle" ? "96s" : "54s") + ";" +
        "--lg-drift-opacity:" + (motion === "none" ? "0" : motion === "subtle" ? "0.3" : "0.42") + ";" +
        "}";
    }

    const WITH_OVERLAY = ${withOverlay ? 'true' : 'false'};
    // The overlay registers on the frame-wide slot registry, so only the
    // overlay-bearing bundle declares the dependency.
    const inject = WITH_OVERLAY ? ["slots"] : [];

/* ---- overlay source (src/overlay.js) ---- */
${overlay}
/* ---- end overlay source ---- */

    function apply(ctx, config) {
      const knobs = readKnobs(config);
      try {
        const previous = document.getElementById(STYLE_ID);
        if (previous) previous.remove();

        const style = document.createElement("style");
        style.id = STYLE_ID;
        style.setAttribute("data-dsh-theme", "liuguang");
        style.textContent = CSS + knobVars(knobs);
        (document.head || document.documentElement).appendChild(style);

        // Live stylesheet from the host: edit liuguang.css, refresh, done.
        // Bounded: text/css only, <= 2 MiB, 3 s budget.
        fetch("/liuguang/theme.css", { cache: "no-store", signal: AbortSignal.timeout(3000) })
          .then((response) => {
            const type = response.headers.get("content-type") || "";
            if (!response.ok || !type.startsWith("text/css")) return null;
            return response.text();
          })
          .then((text) => {
            if (typeof text === "string" && text.length > 1000 && text.length < 2 * 1024 * 1024 && style.isConnected) {
              style.textContent = text;
            }
          })
          .catch(() => {});

        // Liveness beacon: the host logs it, which proves the renderer loaded.
        fetch("/liuguang/ping?loaded=" + encodeURIComponent(${JSON.stringify(id)}), { cache: "no-store" }).catch(() => {});

        if (typeof ctx.effect === "function") ctx.effect(() => () => style.remove());
      } catch (error) {
        console.error("[liuguang] stylesheet failed", error);
      }

      // Controls + pet live on the frame-wide overlay slot. Decorations must
      // never take the app down: a failing overlay is reported and skipped.
      if (WITH_OVERLAY) {
        try {
          mountControls(ctx, config);
        } catch (error) {
          console.warn("[liuguang] overlay failed", error);
        }
      }
    }

    module.exports.apply = apply;
    module.exports.inject = inject;
    return module.exports;
    } catch (error) {
      console.error("[liuguang] factory failed", error);
      throw error;
    }
  }
});
`
  writeFileSync(file, text, 'utf8')
  console.log(`built ${file} (id ${id}, sha ${hash})`)
}

bundle({ id: 'dsh-theme-liuguang', file: join(root, 'lib', 'client.js'), overlay: false })
bundle({
  id: 'dsh-theme-liuguang-browser',
  file: join(root, '..', 'liuguang-browser', 'lib', 'client.js'),
  overlay: true,
})
